package org.example.brackets

class BracketsValidatorKotlin {
    companion object {
        private val pairs = mapOf('(' to ')', '[' to ']', '{' to '}')
        private val closers = pairs.values.toSet()

        /**
         * Проверяет, является ли строка корректной скобочной последовательностью.
         *
         * Поддерживаемые типы скобок: `()`, `[]`, `{}`. Строка считается валидной, если:
         * - каждая открывающая скобка имеет соответствующую закрывающую скобку того же типа;
         * - скобки закрываются в правильном порядке (последняя открытая — первая закрытая, LIFO);
         * - в строке нет символов, кроме `(`, `)`, `[`, `]`, `{`, `}`.
         *
         * Пустая строка считается валидной.
         *
         * Алгоритм: один проход по строке с использованием стека (реализован через [ArrayDeque]).
         * При встрече открывающей скобки в стек кладётся соответствующая ей закрывающая скобка.
         * При встрече закрывающей скобки она сравнивается с вершиной стека: если совпадает —
         * снимается со стека, иначе строка невалидна. Любой символ, не являющийся скобкой,
         * сразу делает строку невалидной.
         *
         * Сложность: O(n) по времени, O(n) по памяти в худшем случае (строка из одних открывающих скобок).
         *
         * @param str проверяемая строка
         * @return `true`, если скобочная последовательность корректна, иначе `false`
         *
         * Примеры:
         * ```
         * isValid("")            // true
         * isValid("{[()()]}")    // true
         * isValid("(])")         // false — несовпадение типов
         * isValid("(")           // false — незакрытая скобка
         * ```
         */
        fun isValid(str: String): Boolean {
            val deque = ArrayDeque<Char>()
            for (char in str) {
                val closer = pairs[char]
                when {
                    closer != null -> deque.addLast(closer)
                    char in closers -> {
                        if (deque.isEmpty() || deque.removeLast() != char) return false
                    }
                    else -> return false
                }
            }
            return deque.isEmpty()
        }
    }
}
